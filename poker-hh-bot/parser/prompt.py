    "PREFLOP only: opening is a 'raise', re-raise is '3bet', re-re-raise is '4bet'. "
    "An all-in shove with no previous bet on that street is a 'bet'; "
    "an all-in shove over a bet/raise is a 'raise'. "

    "GAPS TO CHECK FOR (always ask if unknown): "
